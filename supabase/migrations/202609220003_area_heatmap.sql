-- LIVE CITY: privacy-safe geographic heatmap, independent from places.
-- No raw coordinate is exposed: a cell is published only at k >= 5 sessions.

begin;

create table if not exists public.crowd_area_snapshots (
  id bigint generated by default as identity primary key,
  grid_key text not null,
  center_latitude double precision not null,
  center_longitude double precision not null,
  window_start timestamptz not null,
  window_end timestamptz not null,
  distinct_sessions integer not null,
  observation_count integer not null,
  density_score integer not null check (density_score between 0 and 100),
  created_at timestamptz not null default now(),
  unique (grid_key, window_end)
);

create index if not exists crowd_area_snapshots_window_idx
  on public.crowd_area_snapshots (window_end desc);

create index if not exists crowd_area_snapshots_grid_window_idx
  on public.crowd_area_snapshots (grid_key, window_end desc);

create or replace function public.refresh_crowd_area_snapshots()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  window_end_at timestamptz := date_trunc('minute', now());
  window_start_at timestamptz := date_trunc('minute', now()) - interval '20 minutes';
  inserted_count integer := 0;
begin
  insert into public.crowd_area_snapshots (
    grid_key,
    center_latitude,
    center_longitude,
    window_start,
    window_end,
    distinct_sessions,
    observation_count,
    density_score
  )
  select
    grid_lat::text || ':' || grid_lng::text,
    (grid_lat + 0.5) * 0.004,
    (grid_lng + 0.5) * 0.004,
    window_start_at,
    window_end_at,
    count(distinct session_id)::integer,
    count(*)::integer,
    least(100, round(count(distinct session_id) * 5.0))::integer
  from (
    select
      floor(latitude / 0.004)::integer as grid_lat,
      floor(longitude / 0.004)::integer as grid_lng,
      session_id
    from public.location_observations
    where observed_at >= window_start_at
      and observed_at < window_end_at
  ) observations
  group by grid_lat, grid_lng
  having count(distinct session_id) >= 5
  on conflict (grid_key, window_end) do update
    set distinct_sessions = excluded.distinct_sessions,
        observation_count = excluded.observation_count,
        density_score = excluded.density_score,
        created_at = now();

  get diagnostics inserted_count = row_count;

  delete from public.crowd_area_snapshots
  where window_end < now() - interval '24 hours';

  return jsonb_build_object(
    'cellsPublished', inserted_count,
    'windowStart', window_start_at,
    'windowEnd', window_end_at,
    'privacyThreshold', 5
  );
end;
$$;

revoke all on table public.crowd_area_snapshots from public, anon, authenticated;
revoke all on function public.refresh_crowd_area_snapshots() from public, anon, authenticated;

do $$
declare
  existing_job record;
begin
  for existing_job in
    select jobid from cron.job
    where jobname = 'live-city-area-heatmap-every-20-minutes'
  loop
    perform cron.unschedule(existing_job.jobid);
  end loop;

  perform cron.schedule(
    'live-city-area-heatmap-every-20-minutes',
    '*/20 * * * *',
    $job$select public.refresh_crowd_area_snapshots();$job$
  );
end;
$$;

commit;
