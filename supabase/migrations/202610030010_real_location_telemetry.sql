-- LIVE CITY: opt-in foreground location telemetry for the area heatmap.
-- Raw points are backend-only, expire quickly, and are never returned to clients.

begin;

create table if not exists public.location_observations (
  id bigint generated by default as identity primary key,
  session_id uuid not null,
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180),
  accuracy_meters double precision,
  observed_at timestamptz not null,
  received_at timestamptz not null default now(),
  matched_place_id bigint references public.places(id) on delete set null
);

-- These clauses also make an older manually-created version of the table
-- compatible without overwriting any observations already present.
alter table public.location_observations
  add column if not exists session_id uuid,
  add column if not exists latitude double precision,
  add column if not exists longitude double precision,
  add column if not exists accuracy_meters double precision,
  add column if not exists observed_at timestamptz,
  add column if not exists received_at timestamptz not null default now(),
  add column if not exists matched_place_id bigint references public.places(id) on delete set null;

create index if not exists location_observations_session_observed_idx
  on public.location_observations (session_id, observed_at desc);

-- A session can only contribute one stored point for an instant. Combined
-- with the Edge Function's five-minute gate, this blocks simple replay.
create unique index if not exists location_observations_session_observed_unique_idx
  on public.location_observations (session_id, observed_at);

alter table public.location_observations enable row level security;
revoke all on table public.location_observations from public, anon, authenticated;

comment on table public.location_observations is
  'Backend-only, consented foreground telemetry. Raw coordinates expire within 24 hours and are published only through k-anonymous aggregates.';

commit;
