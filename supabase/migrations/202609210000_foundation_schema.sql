-- LIVE CITY foundational schema.
--
-- The first hosted prototype created these tables manually. Every later
-- migration depends on them, so a clean Supabase project must create them
-- before applying the versioned Crowd Engine migrations.

begin;

create table if not exists public.places (
  id bigint generated by default as identity primary key,
  fsq_place_id text not null unique,
  name text not null,
  address text,
  category text not null check (category in ('aperitivo', 'food', 'nightlife', 'outdoor', 'culture')),
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists places_active_category_idx
  on public.places (is_active, category, id);

create table if not exists public.events (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  category text not null check (category in ('aperitivo', 'food', 'nightlife', 'outdoor', 'culture')),
  venue_name text,
  place_id bigint references public.places(id) on delete set null,
  address text,
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180),
  start_at timestamptz not null,
  end_at timestamptz not null check (end_at > start_at),
  source text not null default 'editorial',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists events_active_window_idx
  on public.events (is_active, start_at, end_at);

create table if not exists public.venue_mappings (
  fsq_place_id text primary key references public.places(fsq_place_id) on delete cascade,
  fsq_name text,
  besttime_venue_id text unique,
  besttime_name text,
  match_status text not null default 'unmatched',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists venue_mappings_besttime_idx
  on public.venue_mappings (besttime_venue_id)
  where besttime_venue_id is not null;

create table if not exists public.venue_crowd_cache (
  besttime_venue_id text primary key,
  crowd_score integer check (crowd_score between 0 and 100),
  activity_level text check (activity_level in ('low', 'medium', 'high', 'very_high')),
  trend text check (trend in ('up', 'stable', 'down')),
  confidence text check (confidence in ('low', 'medium', 'high')),
  fetched_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '1 hour'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists venue_crowd_cache_expiry_idx
  on public.venue_crowd_cache (expires_at);

-- Created here because migrations 002 and 003 index/read this table before the
-- later compatibility migration 010 is applied.
create table if not exists public.location_observations (
  id bigint generated by default as identity primary key,
  session_id uuid not null,
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180),
  accuracy_meters double precision,
  observed_at timestamptz not null,
  received_at timestamptz not null default now(),
  matched_place_id bigint references public.places(id) on delete set null
);

-- Legacy visit tables remain available for migration compatibility. Current
-- crowd calculations consume only k-anonymous crowd_area_snapshots.
create table if not exists public.place_presences (
  id bigint generated by default as identity primary key,
  place_id bigint not null references public.places(id) on delete cascade,
  session_id uuid not null,
  first_seen_at timestamptz not null,
  last_seen_at timestamptz not null,
  presence_confidence double precision not null default 0.5
    check (presence_confidence between 0 and 1),
  created_at timestamptz not null default now(),
  unique (place_id, session_id)
);

create table if not exists public.crowd_snapshots (
  place_id bigint not null references public.places(id) on delete cascade,
  window_start timestamptz not null,
  window_end timestamptz not null,
  confirmed_sessions integer not null default 0 check (confirmed_sessions >= 0),
  weighted_presence double precision not null default 0 check (weighted_presence >= 0),
  average_presence_confidence double precision not null default 0
    check (average_presence_confidence between 0 and 1),
  telemetry_observations integer not null default 0 check (telemetry_observations >= 0),
  telemetry_sessions integer not null default 0 check (telemetry_sessions >= 0),
  telemetry_coverage double precision check (telemetry_coverage between 0 and 1),
  created_at timestamptz not null default now(),
  primary key (place_id, window_end),
  check (window_end > window_start)
);

create table if not exists public.crowd_place_profiles (
  place_id bigint primary key references public.places(id) on delete cascade,
  p25_weighted_presence double precision not null default 0,
  p50_weighted_presence double precision not null default 0,
  p75_weighted_presence double precision not null default 0,
  p90_weighted_presence double precision not null default 0,
  max_weighted_presence double precision not null default 0,
  sample_count integer not null default 0 check (sample_count >= 0),
  distinct_days integer not null default 0 check (distinct_days >= 0),
  confidence double precision not null default 0 check (confidence between 0 and 1),
  refreshed_at timestamptz not null default now()
);

alter table public.places enable row level security;
alter table public.events enable row level security;
alter table public.venue_mappings enable row level security;
alter table public.venue_crowd_cache enable row level security;
alter table public.location_observations enable row level security;
alter table public.place_presences enable row level security;
alter table public.crowd_snapshots enable row level security;
alter table public.crowd_place_profiles enable row level security;

revoke all on table public.events from public, anon, authenticated;
revoke all on table public.venue_mappings from public, anon, authenticated;
revoke all on table public.venue_crowd_cache from public, anon, authenticated;
revoke all on table public.location_observations from public, anon, authenticated;
revoke all on table public.place_presences from public, anon, authenticated;
revoke all on table public.crowd_snapshots from public, anon, authenticated;
revoke all on table public.crowd_place_profiles from public, anon, authenticated;

comment on table public.places is
  'LIVE CITY venue catalogue. Provider identifiers are opaque and never imply verified crowd data.';
comment on table public.venue_mappings is
  'Backend-only mapping between catalogue places and BestTime venue identifiers.';
comment on table public.venue_crowd_cache is
  'Short-lived BestTime response cache. Later migrations add explicit observation provenance.';

commit;
