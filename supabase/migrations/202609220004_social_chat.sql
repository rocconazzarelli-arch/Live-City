-- LIVE CITY social graph and direct messages.
-- Every record is bound to Supabase Auth: anonymous users cannot impersonate a profile.

begin;

create table if not exists public.user_profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  handle text not null unique check (handle ~ '^[a-z0-9_]{3,24}$'),
  display_name text not null check (char_length(display_name) between 1 and 60),
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.social_follows (
  follower_id uuid not null references public.user_profiles (id) on delete cascade,
  following_id uuid not null references public.user_profiles (id) on delete cascade,
  requested_at timestamptz not null default now(),
  accepted_at timestamptz,
  primary key (follower_id, following_id),
  check (follower_id <> following_id)
);

create table if not exists public.direct_threads (
  id uuid primary key default gen_random_uuid(),
  member_one_id uuid not null references public.user_profiles (id) on delete cascade,
  member_two_id uuid not null references public.user_profiles (id) on delete cascade,
  created_at timestamptz not null default now(),
  last_message_at timestamptz,
  check (member_one_id < member_two_id),
  unique (member_one_id, member_two_id)
);

create table if not exists public.direct_messages (
  id bigint generated by default as identity primary key,
  thread_id uuid not null references public.direct_threads (id) on delete cascade,
  sender_id uuid not null references public.user_profiles (id) on delete cascade,
  body text not null check (char_length(trim(body)) between 1 and 1500),
  created_at timestamptz not null default now(),
  read_at timestamptz
);

create index if not exists social_follows_following_idx
  on public.social_follows (following_id, accepted_at desc);
create index if not exists direct_threads_member_one_idx
  on public.direct_threads (member_one_id, last_message_at desc);
create index if not exists direct_threads_member_two_idx
  on public.direct_threads (member_two_id, last_message_at desc);
create index if not exists direct_messages_thread_created_idx
  on public.direct_messages (thread_id, created_at desc);

create or replace function public.touch_user_profile()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists user_profiles_touch_updated_at on public.user_profiles;
create trigger user_profiles_touch_updated_at
before update on public.user_profiles
for each row execute function public.touch_user_profile();

create or replace function public.start_direct_thread(peer_id uuid)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  viewer_id uuid := auth.uid();
  first_id uuid;
  second_id uuid;
  result_thread_id uuid;
begin
  if viewer_id is null then raise exception 'Authentication required'; end if;
  if peer_id = viewer_id then raise exception 'A direct thread requires another profile'; end if;

  if not exists (
    select 1 from public.social_follows
    where follower_id = viewer_id and following_id = peer_id and accepted_at is not null
  ) or not exists (
    select 1 from public.social_follows
    where follower_id = peer_id and following_id = viewer_id and accepted_at is not null
  ) then
    raise exception 'Direct messages require a mutual follow';
  end if;

  first_id := least(viewer_id, peer_id);
  second_id := greatest(viewer_id, peer_id);
  insert into public.direct_threads (member_one_id, member_two_id)
  values (first_id, second_id)
  on conflict (member_one_id, member_two_id) do update
    set member_one_id = excluded.member_one_id
  returning id into result_thread_id;
  return result_thread_id;
end;
$$;

create or replace function public.touch_direct_thread()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.direct_threads set last_message_at = new.created_at where id = new.thread_id;
  return new;
end;
$$;

drop trigger if exists direct_messages_touch_thread on public.direct_messages;
create trigger direct_messages_touch_thread
after insert on public.direct_messages
for each row execute function public.touch_direct_thread();

alter table public.user_profiles enable row level security;
alter table public.social_follows enable row level security;
alter table public.direct_threads enable row level security;
alter table public.direct_messages enable row level security;

create policy "authenticated users can discover profiles" on public.user_profiles
  for select to authenticated using (true);
create policy "users create their own profile" on public.user_profiles
  for insert to authenticated with check (id = auth.uid());
create policy "users update their own profile" on public.user_profiles
  for update to authenticated using (id = auth.uid()) with check (id = auth.uid());

create policy "users read their follow relations" on public.social_follows
  for select to authenticated using (follower_id = auth.uid() or following_id = auth.uid());
create policy "users request follows" on public.social_follows
  for insert to authenticated with check (follower_id = auth.uid());
create policy "recipients accept follow requests" on public.social_follows
  for update to authenticated using (following_id = auth.uid()) with check (following_id = auth.uid());
create policy "users remove their follow relations" on public.social_follows
  for delete to authenticated using (follower_id = auth.uid() or following_id = auth.uid());

create policy "members read their direct threads" on public.direct_threads
  for select to authenticated using (member_one_id = auth.uid() or member_two_id = auth.uid());

create policy "members read their direct messages" on public.direct_messages
  for select to authenticated using (
    exists (
      select 1 from public.direct_threads
      where id = thread_id and (member_one_id = auth.uid() or member_two_id = auth.uid())
    )
  );
create policy "members send direct messages" on public.direct_messages
  for insert to authenticated with check (
    sender_id = auth.uid() and exists (
      select 1 from public.direct_threads
      where id = thread_id and (member_one_id = auth.uid() or member_two_id = auth.uid())
    )
  );
create policy "recipients mark direct messages read" on public.direct_messages
  for update to authenticated using (
    sender_id <> auth.uid() and exists (
      select 1 from public.direct_threads
      where id = thread_id and (member_one_id = auth.uid() or member_two_id = auth.uid())
    )
  ) with check (sender_id <> auth.uid());

revoke all on function public.start_direct_thread(uuid) from public;
grant execute on function public.start_direct_thread(uuid) to authenticated;

commit;
