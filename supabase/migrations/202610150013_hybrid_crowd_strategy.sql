-- LIVE CITY Hybrid: a provider-independent crowd strategy.
-- It combines privacy-safe LIVE CITY telemetry with scheduled mobility,
-- declared events, and historical telemetry. The existing BestTime-backed
-- crowd_estimates table and pipeline remain untouched.

begin;

create table if not exists public.mobility_cell_profiles (
  grid_key text not null,
  center_latitude double precision not null,
  center_longitude double precision not null,
  local_day_type text not null check (local_day_type in ('L', 'S', 'F')),
  local_hour smallint not null check (local_hour between 0 and 23),
  service_intensity double precision not null check (service_intensity >= 0),
  mobility_score integer not null check (mobility_score between 0 and 100),
  stop_count integer not null check (stop_count > 0),
  source_name text not null default 'comune_milano_amat_schedule',
  source_updated_at timestamptz not null,
  refreshed_at timestamptz not null default now(),
  metadata jsonb not null default '{}'::jsonb,
  primary key (grid_key, local_day_type, local_hour)
);

create index if not exists mobility_cell_profiles_slot_idx
  on public.mobility_cell_profiles (local_day_type, local_hour, mobility_score desc);

create table if not exists public.hybrid_crowd_signals (
  id bigint generated by default as identity primary key,
  place_id bigint not null references public.places(id) on delete cascade,
  signal_kind text not null check (signal_kind in ('telemetry', 'mobility', 'event', 'historical')),
  signal_type text not null check (signal_type in ('observed', 'forecast')),
  score integer not null check (score between 0 and 100),
  weight double precision not null check (weight between 0 and 1),
  confidence double precision not null check (confidence between 0 and 1),
  observed_at timestamptz not null,
  valid_until timestamptz not null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists hybrid_crowd_signals_place_time_idx
  on public.hybrid_crowd_signals (place_id, observed_at desc);
create index if not exists hybrid_crowd_signals_valid_until_idx
  on public.hybrid_crowd_signals (valid_until);

create table if not exists public.hybrid_crowd_estimates (
  place_id bigint primary key references public.places(id) on delete cascade,
  score integer not null check (score between 0 and 100),
  activity_level text not null check (activity_level in ('low', 'medium', 'high', 'very_high')),
  trend text not null check (trend in ('up', 'stable', 'down')),
  confidence double precision not null check (confidence between 0 and 1),
  dominant_source text not null check (dominant_source in ('telemetry', 'mobility', 'event', 'historical', 'unavailable')),
  signal_count integer not null default 0 check (signal_count >= 0),
  calculated_at timestamptz not null,
  valid_until timestamptz not null,
  metadata jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create index if not exists hybrid_crowd_estimates_valid_until_idx
  on public.hybrid_crowd_estimates (valid_until);

create table if not exists public.hybrid_historical_slots (
  place_id bigint not null references public.places(id) on delete cascade,
  local_weekday smallint not null check (local_weekday between 1 and 7),
  local_hour smallint not null check (local_hour between 0 and 23),
  average_score double precision not null check (average_score between 0 and 100),
  sample_count integer not null check (sample_count >= 0),
  distinct_days integer not null check (distinct_days >= 0),
  window_start timestamptz not null,
  refreshed_at timestamptz not null default now(),
  primary key (place_id, local_weekday, local_hour)
);

create index if not exists hybrid_historical_slots_lookup_idx
  on public.hybrid_historical_slots (local_weekday, local_hour, sample_count desc);

create or replace function public.refresh_hybrid_historical_slots()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  upserted_count integer := 0;
  observation_window_start timestamptz := now() - interval '90 days';
begin
  with deduplicated_telemetry as (
    select distinct on (place_id, observed_at)
      place_id,
      score,
      observed_at
    from public.crowd_signals
    where observed_at >= observation_window_start
      and source = 'live_city'
      and signal_type = 'observed'
      and metadata ->> 'kind' = 'telemetry'
      and score between 0 and 100
    order by place_id, observed_at, created_at desc
  ),
  slots as (
    select
      place_id,
      extract(isodow from observed_at at time zone 'Europe/Rome')::smallint as local_weekday,
      extract(hour from observed_at at time zone 'Europe/Rome')::smallint as local_hour,
      avg(score)::double precision as average_score,
      count(*)::integer as sample_count,
      count(distinct (observed_at at time zone 'Europe/Rome')::date)::integer as distinct_days
    from deduplicated_telemetry
    group by place_id, local_weekday, local_hour
  )
  insert into public.hybrid_historical_slots (
    place_id, local_weekday, local_hour, average_score, sample_count,
    distinct_days, window_start, refreshed_at
  )
  select
    place_id, local_weekday, local_hour, average_score, sample_count,
    distinct_days, observation_window_start, now()
  from slots
  on conflict (place_id, local_weekday, local_hour) do update
    set average_score = excluded.average_score,
        sample_count = excluded.sample_count,
        distinct_days = excluded.distinct_days,
        window_start = excluded.window_start,
        refreshed_at = excluded.refreshed_at;

  get diagnostics upserted_count = row_count;

  delete from public.hybrid_historical_slots
  where refreshed_at < now() - interval '2 days';

  return jsonb_build_object(
    'slotsUpserted', upserted_count,
    'windowStart', observation_window_start,
    'source', 'live_city_telemetry_only',
    'minimumSamples', 12,
    'minimumDistinctDays', 3
  );
end;
$$;

create or replace function public.purge_expired_hybrid_signals()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  deleted_count integer := 0;
begin
  delete from public.hybrid_crowd_signals
  where valid_until < now() - interval '24 hours';
  get diagnostics deleted_count = row_count;
  return deleted_count;
end;
$$;

alter table public.mobility_cell_profiles enable row level security;
alter table public.hybrid_crowd_signals enable row level security;
alter table public.hybrid_crowd_estimates enable row level security;
alter table public.hybrid_historical_slots enable row level security;

revoke all on table public.mobility_cell_profiles from public, anon, authenticated;
revoke all on table public.hybrid_crowd_signals from public, anon, authenticated;
revoke all on table public.hybrid_crowd_estimates from public, anon, authenticated;
revoke all on table public.hybrid_historical_slots from public, anon, authenticated;
revoke all on function public.refresh_hybrid_historical_slots() from public, anon, authenticated;
revoke all on function public.purge_expired_hybrid_signals() from public, anon, authenticated;

do $$
declare
  existing_job record;
begin
  for existing_job in
    select jobid from cron.job
    where jobname in (
      'live-city-hybrid-crowd-every-20-minutes',
      'live-city-hybrid-history-nightly',
      'live-city-mobility-source-daily',
      'live-city-hybrid-signal-retention'
    )
  loop
    perform cron.unschedule(existing_job.jobid);
  end loop;

  perform cron.schedule(
    'live-city-hybrid-crowd-every-20-minutes',
    '7,27,47 * * * *',
    $job$
      select net.http_post(
        url := 'https://qmskozzidachccwbtejd.supabase.co/functions/v1/hybrid-crowd-refresh',
        headers := jsonb_build_object(
          'Content-Type', 'application/json',
          'x-refresh-secret', (
            select decrypted_secret from vault.decrypted_secrets
            where name = 'crowd_pipeline_secret' limit 1
          )
        ),
        body := '{}'::jsonb,
        timeout_milliseconds := 140000
      );
    $job$
  );

  perform cron.schedule(
    'live-city-hybrid-history-nightly',
    '23 2 * * *',
    $job$select public.refresh_hybrid_historical_slots();$job$
  );

  perform cron.schedule(
    'live-city-mobility-source-daily',
    '41 3 * * *',
    $job$
      select net.http_post(
        url := 'https://qmskozzidachccwbtejd.supabase.co/functions/v1/mobility-source-refresh',
        headers := jsonb_build_object(
          'Content-Type', 'application/json',
          'x-refresh-secret', (
            select decrypted_secret from vault.decrypted_secrets
            where name = 'crowd_pipeline_secret' limit 1
          )
        ),
        body := '{}'::jsonb,
        timeout_milliseconds := 140000
      );
    $job$
  );

  perform cron.schedule(
    'live-city-hybrid-signal-retention',
    '29 * * * *',
    $job$select public.purge_expired_hybrid_signals();$job$
  );
end;
$$;

comment on table public.mobility_cell_profiles is
  'Scheduled public-transport supply by privacy grid cell. This is a mobility proxy, never verified live foot traffic.';
comment on table public.hybrid_crowd_estimates is
  'Provider-independent estimates for LIVE CITY Hybrid. The BestTime-backed crowd_estimates table remains separate.';

commit;
