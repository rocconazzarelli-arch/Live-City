-- LIVE CITY private beta: telemetry arrives as a coarse grid cell, never as a
-- precise device fix. Consent is versioned and provider work is auditable.

begin;

alter table public.location_observations
  add column if not exists grid_lat integer,
  add column if not exists grid_lng integer,
  add column if not exists consent_version text not null default 'legacy-unknown';

create index if not exists location_observations_grid_time_idx
  on public.location_observations (grid_lat, grid_lng, observed_at desc)
  where grid_lat is not null and grid_lng is not null;

comment on column public.location_observations.latitude is
  'Canonical centre of a coarse privacy grid cell; not a device GPS coordinate.';
comment on column public.location_observations.longitude is
  'Canonical centre of a coarse privacy grid cell; not a device GPS coordinate.';
comment on column public.location_observations.consent_version is
  'Version of the explicit in-app consent accepted before the anonymised cell was submitted.';

create or replace function public.refresh_crowd_area_snapshots()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  window_end_at timestamptz := date_trunc('minute', now());
  window_start_at timestamptz := date_trunc('minute', now()) - interval '20 minutes';
  inserted_count integer := 0;
begin
  insert into public.crowd_area_snapshots (
    grid_key, center_latitude, center_longitude, window_start, window_end,
    distinct_sessions, observation_count, density_score
  )
  select
    grid_lat::text || ':' || grid_lng::text,
    (grid_lat + 0.5) * 0.004,
    (grid_lng + 0.5) * 0.004,
    window_start_at,
    window_end_at,
    count(distinct session_id)::integer,
    count(*)::integer,
    least(100, round(count(distinct session_id) * 5.0))::integer
  from public.location_observations
  where observed_at >= window_start_at
    and observed_at < window_end_at
    and consent_version = '2026-10-private-beta-1'
    and grid_lat is not null
    and grid_lng is not null
  group by grid_lat, grid_lng
  having count(distinct session_id) >= 5
  on conflict (grid_key, window_end) do update
    set distinct_sessions = excluded.distinct_sessions,
        observation_count = excluded.observation_count,
        density_score = excluded.density_score,
        created_at = now();

  get diagnostics inserted_count = row_count;
  delete from public.crowd_area_snapshots where window_end < now() - interval '24 hours';
  return jsonb_build_object('cellsPublished', inserted_count, 'windowStart', window_start_at, 'windowEnd', window_end_at, 'privacyThreshold', 5);
end;
$$;

create table if not exists public.crowd_provider_runs (
  id bigint generated by default as identity primary key,
  provider text not null,
  started_at timestamptz not null default now(),
  completed_at timestamptz not null default now(),
  requested_count integer not null default 0 check (requested_count >= 0),
  live_written_count integer not null default 0 check (live_written_count >= 0),
  unavailable_count integer not null default 0 check (unavailable_count >= 0),
  failure_count integer not null default 0 check (failure_count >= 0),
  status text not null check (status in ('success', 'partial', 'failed')),
  metadata jsonb not null default '{}'::jsonb
);

create index if not exists crowd_provider_runs_provider_completed_idx
  on public.crowd_provider_runs (provider, completed_at desc);

alter table public.crowd_provider_runs enable row level security;
revoke all on table public.crowd_provider_runs from public, anon, authenticated;

commit;
