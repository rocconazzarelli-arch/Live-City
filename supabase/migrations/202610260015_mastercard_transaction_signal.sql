-- LIVE CITY: privacy-minimised Mastercard transaction activity signal.
--
-- Mastercard Transaction Notifications cover only explicitly enrolled cards.
-- A purchase is not a person counter, so this migration stores no PAN, card
-- reference, amount or customer identity. It keeps a salted transaction hash
-- briefly for idempotency, publishes only >=5-transaction venue aggregates,
-- and normalises each venue against its own historical distribution.

begin;

create table if not exists public.mastercard_merchant_mappings (
  id bigint generated by default as identity primary key,
  place_id bigint not null references public.places(id) on delete cascade,
  mastercard_merchant_id text not null unique,
  source_coverage double precision
    check (source_coverage between 0 and 1),
  match_confidence double precision not null default 1
    check (match_confidence between 0 and 1),
  mapping_source text not null default 'manual',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists mastercard_merchant_mappings_place_idx
  on public.mastercard_merchant_mappings (place_id)
  where is_active;

create table if not exists public.mastercard_transaction_events (
  provider_transaction_hash text primary key,
  place_id bigint not null references public.places(id) on delete cascade,
  event_stage text not null check (event_stage in ('authorization', 'clearing')),
  transaction_status text not null check (transaction_status in ('approved', 'reversed')),
  occurred_at timestamptz not null,
  received_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists mastercard_transaction_events_place_time_idx
  on public.mastercard_transaction_events (place_id, occurred_at desc)
  where transaction_status = 'approved';

create table if not exists public.mastercard_transaction_snapshots (
  place_id bigint not null references public.places(id) on delete cascade,
  window_start timestamptz not null,
  window_end timestamptz not null,
  transaction_count integer not null check (transaction_count >= 5),
  source_coverage double precision
    check (source_coverage between 0 and 1),
  created_at timestamptz not null default now(),
  primary key (place_id, window_end),
  check (window_end > window_start)
);

create index if not exists mastercard_transaction_snapshots_latest_idx
  on public.mastercard_transaction_snapshots (window_end desc, place_id);

create table if not exists public.mastercard_transaction_profiles (
  place_id bigint primary key references public.places(id) on delete cascade,
  p25_transaction_count double precision not null check (p25_transaction_count >= 0),
  p50_transaction_count double precision not null check (p50_transaction_count >= 0),
  p75_transaction_count double precision not null check (p75_transaction_count >= 0),
  p90_transaction_count double precision not null check (p90_transaction_count >= 0),
  max_transaction_count double precision not null check (max_transaction_count >= 0),
  sample_count integer not null check (sample_count >= 0),
  distinct_days integer not null check (distinct_days >= 0),
  confidence double precision not null check (confidence between 0 and 1),
  refreshed_at timestamptz not null default now()
);

create or replace function public.refresh_mastercard_transaction_snapshots()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  window_end_at timestamptz := date_bin(
    interval '20 minutes',
    now(),
    timestamptz '2001-01-01 00:00:00+00'
  );
  replay_window_start_at timestamptz;
  published_count integer := 0;
begin
  -- Rebuild six completed windows so a slightly delayed provider notification
  -- can still reach the historical venue profile without being shown as a
  -- current signal after its 40-minute validity period.
  replay_window_start_at := window_end_at - interval '2 hours';

  -- Reversals can lower a previously published bucket below the privacy
  -- threshold. Remove the replay range first so such a bucket disappears
  -- instead of surviving from an earlier refresh.
  delete from public.mastercard_transaction_snapshots
  where window_end > replay_window_start_at
    and window_end <= window_end_at;

  with bucketed as (
    select
      place_id,
      date_bin(
        interval '20 minutes',
        occurred_at,
        timestamptz '2001-01-01 00:00:00+00'
      ) as bucket_start
    from public.mastercard_transaction_events
    where occurred_at >= replay_window_start_at
      and occurred_at < window_end_at
      and transaction_status = 'approved'
  )
  insert into public.mastercard_transaction_snapshots (
    place_id, window_start, window_end, transaction_count, source_coverage
  )
  select
    bucketed.place_id,
    bucketed.bucket_start,
    bucketed.bucket_start + interval '20 minutes',
    count(*)::integer,
    (
      select max(mapping.source_coverage)
      from public.mastercard_merchant_mappings as mapping
      where mapping.place_id = bucketed.place_id
        and mapping.is_active
    )
  from bucketed
  group by bucketed.place_id, bucketed.bucket_start
  having count(*) >= 5
  on conflict (place_id, window_end) do update
    set transaction_count = excluded.transaction_count,
        source_coverage = excluded.source_coverage,
        created_at = now();

  get diagnostics published_count = row_count;

  return jsonb_build_object(
    'snapshotsPublished', published_count,
    'replayWindowStart', replay_window_start_at,
    'windowEnd', window_end_at,
    'privacyThreshold', 5,
    'dataClass', 'transaction_proxy'
  );
end;
$$;

create or replace function public.refresh_mastercard_transaction_profiles()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  upserted_count integer := 0;
begin
  insert into public.mastercard_transaction_profiles (
    place_id,
    p25_transaction_count,
    p50_transaction_count,
    p75_transaction_count,
    p90_transaction_count,
    max_transaction_count,
    sample_count,
    distinct_days,
    confidence,
    refreshed_at
  )
  select
    place_id,
    percentile_cont(0.25) within group (order by transaction_count),
    percentile_cont(0.50) within group (order by transaction_count),
    percentile_cont(0.75) within group (order by transaction_count),
    percentile_cont(0.90) within group (order by transaction_count),
    max(transaction_count)::double precision,
    count(*)::integer,
    count(distinct (window_end at time zone 'Europe/Rome')::date)::integer,
    least(
      0.9,
      0.35 + count(*)::double precision / 120.0
        + count(distinct (window_end at time zone 'Europe/Rome')::date)::double precision / 40.0
    ),
    now()
  from public.mastercard_transaction_snapshots
  where window_end >= now() - interval '90 days'
  group by place_id
  having count(*) >= 12
     and count(distinct (window_end at time zone 'Europe/Rome')::date) >= 3
  on conflict (place_id) do update
    set p25_transaction_count = excluded.p25_transaction_count,
        p50_transaction_count = excluded.p50_transaction_count,
        p75_transaction_count = excluded.p75_transaction_count,
        p90_transaction_count = excluded.p90_transaction_count,
        max_transaction_count = excluded.max_transaction_count,
        sample_count = excluded.sample_count,
        distinct_days = excluded.distinct_days,
        confidence = excluded.confidence,
        refreshed_at = excluded.refreshed_at;

  get diagnostics upserted_count = row_count;
  return jsonb_build_object('profilesUpserted', upserted_count, 'windowDays', 90);
end;
$$;

create or replace function public.purge_mastercard_transaction_events()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  deleted_count integer := 0;
begin
  delete from public.mastercard_transaction_events
  where received_at < now() - interval '48 hours';
  get diagnostics deleted_count = row_count;
  return deleted_count;
end;
$$;

alter table public.crowd_historical_slots
  add column if not exists mastercard_samples integer not null default 0
    check (mastercard_samples >= 0);

create or replace function public.refresh_crowd_historical_slots()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  upserted_count integer := 0;
  observation_window_start timestamptz := now() - interval '90 days';
begin
  with deduplicated_observations as (
    select distinct on (place_id, source, observed_at)
      place_id,
      source,
      score,
      observed_at
    from public.crowd_signals
    where observed_at >= observation_window_start
      and signal_type = 'observed'
      and metadata ->> 'kind' in ('besttime', 'mastercard', 'telemetry')
      and score between 0 and 100
    order by place_id, source, observed_at, created_at desc
  ),
  slots as (
    select
      place_id,
      extract(isodow from observed_at at time zone 'Europe/Rome')::smallint as local_weekday,
      extract(hour from observed_at at time zone 'Europe/Rome')::smallint as local_hour,
      avg(score)::double precision as average_score,
      count(*)::integer as sample_count,
      count(distinct (observed_at at time zone 'Europe/Rome')::date)::integer as distinct_days,
      count(*) filter (where source = 'besttime')::integer as besttime_samples,
      count(*) filter (where source = 'mastercard')::integer as mastercard_samples,
      count(*) filter (where source = 'live_city')::integer as telemetry_samples
    from deduplicated_observations
    group by place_id, local_weekday, local_hour
  )
  insert into public.crowd_historical_slots (
    place_id, local_weekday, local_hour, average_score, sample_count,
    distinct_days, besttime_samples, mastercard_samples, telemetry_samples,
    window_start, refreshed_at
  )
  select
    place_id, local_weekday, local_hour, average_score, sample_count,
    distinct_days, besttime_samples, mastercard_samples, telemetry_samples,
    observation_window_start, now()
  from slots
  on conflict (place_id, local_weekday, local_hour) do update
    set average_score = excluded.average_score,
        sample_count = excluded.sample_count,
        distinct_days = excluded.distinct_days,
        besttime_samples = excluded.besttime_samples,
        mastercard_samples = excluded.mastercard_samples,
        telemetry_samples = excluded.telemetry_samples,
        window_start = excluded.window_start,
        refreshed_at = excluded.refreshed_at;

  get diagnostics upserted_count = row_count;
  delete from public.crowd_historical_slots
  where refreshed_at < now() - interval '2 days';

  return jsonb_build_object(
    'slotsUpserted', upserted_count,
    'windowStart', observation_window_start,
    'minimumSamples', 12,
    'minimumDistinctDays', 3,
    'sources', jsonb_build_array('besttime', 'mastercard', 'telemetry')
  );
end;
$$;

alter table public.mastercard_merchant_mappings enable row level security;
alter table public.mastercard_transaction_events enable row level security;
alter table public.mastercard_transaction_snapshots enable row level security;
alter table public.mastercard_transaction_profiles enable row level security;

revoke all on table public.mastercard_merchant_mappings from public, anon, authenticated;
revoke all on table public.mastercard_transaction_events from public, anon, authenticated;
revoke all on table public.mastercard_transaction_snapshots from public, anon, authenticated;
revoke all on table public.mastercard_transaction_profiles from public, anon, authenticated;
revoke all on function public.refresh_mastercard_transaction_snapshots() from public, anon, authenticated;
revoke all on function public.refresh_mastercard_transaction_profiles() from public, anon, authenticated;
revoke all on function public.purge_mastercard_transaction_events() from public, anon, authenticated;

do $$
declare
  existing_job record;
begin
  for existing_job in
    select jobid from cron.job
    where jobname in (
      'live-city-mastercard-profiles-nightly',
      'live-city-mastercard-event-retention'
    )
  loop
    perform cron.unschedule(existing_job.jobid);
  end loop;

  perform cron.schedule(
    'live-city-mastercard-profiles-nightly',
    '18 2 * * *',
    $job$select public.refresh_mastercard_transaction_profiles();$job$
  );

  perform cron.schedule(
    'live-city-mastercard-event-retention',
    '37 * * * *',
    $job$select public.purge_mastercard_transaction_events();$job$
  );
end;
$$;

comment on table public.mastercard_transaction_events is
  'Short-lived, de-identified transaction occurrences. No PAN, amount, card reference or customer identity is stored.';
comment on table public.mastercard_transaction_snapshots is
  'K-anonymous 20-minute Mastercard transaction counts used only as a venue activity proxy, never as a person count.';
comment on table public.mastercard_transaction_profiles is
  'Per-venue transaction-count percentiles used to normalize Mastercard activity without comparing unlike venues.';

commit;
