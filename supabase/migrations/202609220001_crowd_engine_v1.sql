-- LIVE CITY Crowd Engine V1
-- Additive and rerunnable: it completes the early prototype tables without
-- deleting the legacy columns used by the already deployed functions.

begin;

create table if not exists public.crowd_signals (
  id bigint generated by default as identity primary key,
  place_id bigint not null references public.places(id) on delete cascade,
  source text not null,
  signal_type text not null,
  score double precision not null,
  weight double precision not null default 1,
  confidence double precision not null,
  observed_at timestamptz not null,
  valid_until timestamptz not null,
  expires_at timestamptz,
  target_at timestamptz not null default now(),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.crowd_signals
  add column if not exists weight double precision,
  add column if not exists valid_until timestamptz;

update public.crowd_signals
set
  weight = coalesce(weight, 1),
  valid_until = coalesce(valid_until, expires_at, observed_at + interval '1 hour')
where weight is null or valid_until is null;

alter table public.crowd_signals
  alter column weight set default 1,
  alter column weight set not null,
  alter column valid_until set not null;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'crowd_signals_weight_check'
      and conrelid = 'public.crowd_signals'::regclass
  ) then
    alter table public.crowd_signals
      add constraint crowd_signals_weight_check check (weight >= 0 and weight <= 1);
  end if;
end;
$$;

create index if not exists crowd_signals_place_observed_idx
  on public.crowd_signals (place_id, observed_at desc);

create index if not exists crowd_signals_valid_until_idx
  on public.crowd_signals (valid_until);

create table if not exists public.crowd_estimates (
  id bigint generated by default as identity primary key,
  place_id bigint not null references public.places(id) on delete cascade,
  estimate_type text not null default 'live',
  target_at timestamptz not null default now(),
  crowd_score integer not null default 0,
  score integer not null default 0,
  activity_level text not null default 'low',
  trend text not null default 'stable',
  confidence double precision not null default 0.3,
  live_signal_score double precision,
  historical_score double precision,
  external_forecast_score double precision,
  sample_size integer,
  dominant_source text not null default 'temporal',
  signal_count integer not null default 0,
  generated_at timestamptz not null default now(),
  calculated_at timestamptz not null default now(),
  expires_at timestamptz,
  valid_until timestamptz not null default (now() + interval '30 minutes'),
  metadata jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

alter table public.crowd_estimates
  add column if not exists score integer,
  add column if not exists dominant_source text,
  add column if not exists signal_count integer,
  add column if not exists calculated_at timestamptz,
  add column if not exists valid_until timestamptz,
  add column if not exists updated_at timestamptz;

update public.crowd_estimates
set
  score = coalesce(score, crowd_score),
  dominant_source = coalesce(dominant_source, 'legacy_cache'),
  signal_count = coalesce(signal_count, 1),
  calculated_at = coalesce(calculated_at, generated_at, now()),
  valid_until = coalesce(valid_until, expires_at, now()),
  updated_at = coalesce(updated_at, generated_at, now())
where score is null
   or dominant_source is null
   or signal_count is null
   or calculated_at is null
   or valid_until is null
   or updated_at is null;

alter table public.crowd_estimates
  alter column score set default 0,
  alter column score set not null,
  alter column dominant_source set default 'temporal',
  alter column dominant_source set not null,
  alter column signal_count set default 0,
  alter column signal_count set not null,
  alter column calculated_at set default now(),
  alter column calculated_at set not null,
  alter column valid_until set default (now() + interval '30 minutes'),
  alter column valid_until set not null,
  alter column updated_at set default now(),
  alter column updated_at set not null;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'crowd_estimates_score_check'
      and conrelid = 'public.crowd_estimates'::regclass
  ) then
    alter table public.crowd_estimates
      add constraint crowd_estimates_score_check check (score between 0 and 100);
  end if;

  if not exists (
    select 1 from pg_constraint
    where conname = 'crowd_estimates_signal_count_check'
      and conrelid = 'public.crowd_estimates'::regclass
  ) then
    alter table public.crowd_estimates
      add constraint crowd_estimates_signal_count_check check (signal_count >= 0);
  end if;
end;
$$;

-- The existing table is empty in the inspected project. This index changes the
-- prototype's forecast-oriented table into one current estimate per place while
-- keeping all legacy columns for backwards compatibility.
create unique index if not exists crowd_estimates_one_per_place_idx
  on public.crowd_estimates (place_id);

create index if not exists crowd_estimates_valid_until_idx
  on public.crowd_estimates (valid_until);

create or replace function public.set_crowd_estimate_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists crowd_estimates_set_updated_at on public.crowd_estimates;
create trigger crowd_estimates_set_updated_at
before update on public.crowd_estimates
for each row execute function public.set_crowd_estimate_updated_at();

alter table public.crowd_signals enable row level security;
alter table public.crowd_estimates enable row level security;

-- Raw signals remain backend-only. The public API normally reads estimates
-- through places-read, but this policy also permits safe direct reads of only
-- currently valid aggregate estimates.
do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'crowd_estimates'
      and policyname = 'Public can read current crowd estimates'
  ) then
    create policy "Public can read current crowd estimates"
      on public.crowd_estimates
      for select
      to anon, authenticated
      using (valid_until >= now());
  end if;
end;
$$;

revoke all on table public.crowd_signals from anon, authenticated;
grant select on table public.crowd_estimates to anon, authenticated;

comment on table public.crowd_signals is
  'Raw, expiring inputs used by LIVE CITY Crowd Engine V1. Not exposed to clients.';
comment on table public.crowd_estimates is
  'One current aggregate crowd estimate per place; legacy columns are retained for compatibility.';

commit;
