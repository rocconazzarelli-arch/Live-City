-- LIVE CITY: safety controls for private social interactions.
-- A block prevents new direct-message writes in both directions.

begin;

create table if not exists public.social_blocks (
  blocker_id uuid not null references public.user_profiles (id) on delete cascade,
  blocked_id uuid not null references public.user_profiles (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (blocker_id, blocked_id),
  check (blocker_id <> blocked_id)
);

create table if not exists public.user_reports (
  id bigint generated by default as identity primary key,
  reporter_id uuid not null references public.user_profiles (id) on delete cascade,
  reported_id uuid not null references public.user_profiles (id) on delete cascade,
  reason text not null check (char_length(trim(reason)) between 3 and 500),
  created_at timestamptz not null default now(),
  check (reporter_id <> reported_id)
);

create index if not exists social_blocks_blocked_idx on public.social_blocks (blocked_id);
create index if not exists user_reports_reported_idx on public.user_reports (reported_id, created_at desc);

alter table public.social_blocks enable row level security;
alter table public.user_reports enable row level security;

create policy "users read their own blocks" on public.social_blocks
  for select to authenticated using (blocker_id = auth.uid());
-- Blocks are created exclusively via block_social_user(), which also removes
-- the two follow relationships atomically.
create policy "users remove their own blocks" on public.social_blocks
  for delete to authenticated using (blocker_id = auth.uid());

create policy "users submit reports" on public.user_reports
  for insert to authenticated with check (reporter_id = auth.uid());
create policy "users read their own reports" on public.user_reports
  for select to authenticated using (reporter_id = auth.uid());

create or replace function public.block_social_user(target_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  viewer_id uuid := auth.uid();
begin
  if viewer_id is null then raise exception 'Authentication required'; end if;
  if target_id = viewer_id then raise exception 'A user cannot block themselves'; end if;
  if not exists (select 1 from public.user_profiles where id = target_id) then
    raise exception 'Profile not found';
  end if;

  insert into public.social_blocks (blocker_id, blocked_id)
  values (viewer_id, target_id)
  on conflict (blocker_id, blocked_id) do nothing;

  delete from public.social_follows
  where (follower_id = viewer_id and following_id = target_id)
     or (follower_id = target_id and following_id = viewer_id);
end;
$$;

create or replace function public.start_direct_thread(peer_id uuid)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  viewer_id uuid := auth.uid();
  first_id uuid;
  second_id uuid;
  result_thread_id uuid;
begin
  if viewer_id is null then raise exception 'Authentication required'; end if;
  if peer_id = viewer_id then raise exception 'A direct thread requires another profile'; end if;
  if exists (
    select 1 from public.social_blocks
    where (blocker_id = viewer_id and blocked_id = peer_id)
       or (blocker_id = peer_id and blocked_id = viewer_id)
  ) then raise exception 'This conversation is unavailable'; end if;
  if not exists (
    select 1 from public.social_follows
    where follower_id = viewer_id and following_id = peer_id and accepted_at is not null
  ) or not exists (
    select 1 from public.social_follows
    where follower_id = peer_id and following_id = viewer_id and accepted_at is not null
  ) then raise exception 'Direct messages require a mutual follow'; end if;

  first_id := least(viewer_id, peer_id);
  second_id := greatest(viewer_id, peer_id);
  insert into public.direct_threads (member_one_id, member_two_id)
  values (first_id, second_id)
  on conflict (member_one_id, member_two_id) do update set member_one_id = excluded.member_one_id
  returning id into result_thread_id;
  return result_thread_id;
end;
$$;

drop policy if exists "members send direct messages" on public.direct_messages;
create policy "members send direct messages when unblocked" on public.direct_messages
  for insert to authenticated with check (
    sender_id = auth.uid()
    and exists (
      select 1 from public.direct_threads
      where id = thread_id and (member_one_id = auth.uid() or member_two_id = auth.uid())
    )
    and not exists (
      select 1 from public.direct_threads thread
      join public.social_blocks block on (
        (block.blocker_id = thread.member_one_id and block.blocked_id = thread.member_two_id)
        or (block.blocker_id = thread.member_two_id and block.blocked_id = thread.member_one_id)
      )
      where thread.id = thread_id
    )
  );

revoke all on function public.start_direct_thread(uuid) from public;
grant execute on function public.start_direct_thread(uuid) to authenticated;
revoke all on function public.block_social_user(uuid) from public;
grant execute on function public.block_social_user(uuid) to authenticated;

commit;
